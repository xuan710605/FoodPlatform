CREATE TABLE IF NOT EXISTS product_ingredient_snapshot (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  snapshot_code VARCHAR(48) NOT NULL,
  product_id BIGINT UNSIGNED NOT NULL,
  spec_id BIGINT UNSIGNED NULL,
  version_no INT UNSIGNED NOT NULL DEFAULT 1,
  entity_type VARCHAR(16) NOT NULL DEFAULT 'INGREDIENT' COMMENT 'INGREDIENT/ADDITIVE/UNKNOWN',
  entity_code VARCHAR(40) NOT NULL COMMENT 'ingredient_code或additive_code；未知项使用UNK编码',
  normalized_name VARCHAR(160) NOT NULL,
  relation_type VARCHAR(24) NOT NULL COMMENT 'CONTAINS/MAY_CONTAIN/UNKNOWN',
  raw_fragment VARCHAR(500) NULL,
  confidence DECIMAL(5,4) NULL,
  source_code VARCHAR(40) NOT NULL,
  audit_status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
  graph_sync_status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
  effective_from DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  effective_to DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_ingredient_snapshot_code (snapshot_code),
  UNIQUE KEY uk_ingredient_snapshot_version (product_id, version_no, entity_code, relation_type),
  KEY idx_ingredient_snapshot_entity (entity_code, relation_type, audit_status),
  KEY idx_ingredient_snapshot_product_active (product_id, effective_to),
  CONSTRAINT fk_ingredient_snapshot_product FOREIGN KEY (product_id) REFERENCES product(id) ON DELETE CASCADE,
  CONSTRAINT fk_ingredient_snapshot_spec FOREIGN KEY (spec_id) REFERENCES product_spec(id) ON DELETE SET NULL,
  CONSTRAINT chk_ingredient_relation CHECK (relation_type IN ('CONTAINS','MAY_CONTAIN','UNKNOWN')),
  CONSTRAINT chk_ingredient_confidence CHECK (confidence IS NULL OR (confidence BETWEEN 0 AND 1))
) ENGINE=InnoDB COMMENT='与原始配料文本分离的结构化配料版本快照';

CREATE TABLE IF NOT EXISTS product_nutrition (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  product_id BIGINT UNSIGNED NOT NULL,
  spec_id BIGINT UNSIGNED NULL,
  nutrient_code VARCHAR(40) NOT NULL,
  nutrient_name VARCHAR(120) NOT NULL,
  nutrient_value DECIMAL(14,4) NULL COMMENT '空值表示暂无数据，禁止伪造',
  unit VARCHAR(24) NOT NULL,
  basis VARCHAR(32) NOT NULL COMMENT 'PER_100G/PER_100ML/PER_SERVING',
  basis_quantity DECIMAL(10,3) NOT NULL DEFAULT 100,
  source_code VARCHAR(40) NOT NULL,
  audit_status VARCHAR(24) NOT NULL DEFAULT 'APPROVED',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_product_nutrition (product_id, spec_id, nutrient_code, basis),
  KEY idx_nutrition_query (nutrient_code, basis, nutrient_value),
  CONSTRAINT fk_product_nutrition_product FOREIGN KEY (product_id) REFERENCES product(id) ON DELETE CASCADE,
  CONSTRAINT fk_product_nutrition_spec FOREIGN KEY (spec_id) REFERENCES product_spec(id) ON DELETE SET NULL,
  CONSTRAINT chk_nutrition_value CHECK (nutrient_value IS NULL OR nutrient_value >= 0)
) ENGINE=InnoDB COMMENT='商品营养值，保存数值、单位与基准';

