  CONSTRAINT fk_user_preference_user FOREIGN KEY (user_id) REFERENCES sys_user(id) ON DELETE CASCADE,
  CONSTRAINT chk_preference_type CHECK (preference_type IN ('EXCLUDE','PREFER')),
  CONSTRAINT chk_preference_strength CHECK (strength BETWEEN 0 AND 100)
) ENGINE=InnoDB COMMENT='用户成分排除与偏好设置';

