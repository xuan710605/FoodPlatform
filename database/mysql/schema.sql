  CONSTRAINT fk_sys_user_role_role FOREIGN KEY (role_id) REFERENCES sys_role(id) ON DELETE RESTRICT,
  CONSTRAINT fk_sys_user_role_grantor FOREIGN KEY (granted_by) REFERENCES sys_user(id) ON DELETE SET NULL
