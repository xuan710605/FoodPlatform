-- FoodPlatform schema. Tested with MySQL 9.7.1.
-- Database: food_platform
SET NAMES utf8mb4;
SET time_zone = '+08:00';

CREATE DATABASE IF NOT EXISTS food_platform
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_0900_ai_ci;
USE food_platform;

CREATE TABLE IF NOT EXISTS sys_user (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '内部用户主键',
  user_code VARCHAR(32) NOT NULL COMMENT '跨系统用户业务编码',
  username VARCHAR(64) NOT NULL COMMENT '登录账号',
  password_hash VARCHAR(255) NOT NULL COMMENT '强哈希密码，不保存明文',
  phone VARCHAR(32) NULL,
  email VARCHAR(128) NULL,
  user_type VARCHAR(32) NOT NULL DEFAULT 'CONSUMER' COMMENT 'CONSUMER/MERCHANT/ADMIN/KNOWLEDGE_ADMIN/OPS',
  status VARCHAR(24) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE/FROZEN/PENDING/DISABLED',
  last_login_at DATETIME(3) NULL,
  password_changed_at DATETIME(3) NULL,
  is_deleted TINYINT(1) NOT NULL DEFAULT 0,
  deleted_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_sys_user_code (user_code),
  UNIQUE KEY uk_sys_user_username (username),
  UNIQUE KEY uk_sys_user_phone (phone),
  UNIQUE KEY uk_sys_user_email (email),
  KEY idx_sys_user_type_status (user_type, status),
  KEY idx_sys_user_created_at (created_at)
) ENGINE=InnoDB COMMENT='系统用户与认证账号';

