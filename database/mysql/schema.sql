CREATE TABLE IF NOT EXISTS product (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  product_code VARCHAR(40) NOT NULL COMMENT 'MySQL与Neo4j统一商品业务ID',
  merchant_id BIGINT UNSIGNED NOT NULL,
  brand_id BIGINT UNSIGNED NOT NULL,
  category_id BIGINT UNSIGNED NOT NULL,
  product_name VARCHAR(200) NOT NULL,
  subtitle VARCHAR(255) NULL,
  description TEXT NULL,
  raw_ingredient_text TEXT NOT NULL COMMENT '商品包装上的原始配料文本，不被标准化结果覆盖',
  allergen_notice TEXT NULL,
  match_status VARCHAR(24) NOT NULL DEFAULT 'INFORMATION_INSUFFICIENT' COMMENT 'FULL_MATCH/RISK/NOT_MATCH/INFORMATION_INSUFFICIENT',
  match_reason VARCHAR(500) NULL,
  evidence_text VARCHAR(1000) NULL,
  info_source VARCHAR(500) NULL,
  sale_status VARCHAR(24) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT/ON_SALE/OFF_SALE/SUSPENDED',
  review_status VARCHAR(24) NOT NULL DEFAULT 'DRAFT' COMMENT 'DRAFT/PENDING/APPROVED/REJECTED/NEED_MORE_INFO',
  neo4j_node_key VARCHAR(64) NOT NULL COMMENT '默认等于product_code，不使用Neo4j内部ID',
  graph_sync_status VARCHAR(24) NOT NULL DEFAULT 'PENDING',
  graph_version VARCHAR(32) NULL,
  is_deleted TINYINT(1) NOT NULL DEFAULT 0,
  deleted_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_product_code (product_code),
  UNIQUE KEY uk_product_neo4j_key (neo4j_node_key),
  KEY idx_product_merchant_status (merchant_id, sale_status, review_status),
  KEY idx_product_brand_status (brand_id, sale_status),
  KEY idx_product_category_status (category_id, sale_status),
  KEY idx_product_name (product_name),
  CONSTRAINT fk_product_merchant FOREIGN KEY (merchant_id) REFERENCES merchant(id) ON DELETE RESTRICT,
  CONSTRAINT fk_product_brand FOREIGN KEY (brand_id) REFERENCES brand(id) ON DELETE RESTRICT,
  CONSTRAINT fk_product_category FOREIGN KEY (category_id) REFERENCES category(id) ON DELETE RESTRICT
) ENGINE=InnoDB COMMENT='食品商品主数据与审核/图谱同步状态';

