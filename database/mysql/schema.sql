CREATE TABLE IF NOT EXISTS user_ingredient_preference (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  preference_code VARCHAR(40) NOT NULL,
  user_id BIGINT UNSIGNED NOT NULL,
  preference_type VARCHAR(16) NOT NULL COMMENT 'EXCLUDE/PREFER',
  ingredient_code VARCHAR(40) NOT NULL COMMENT '与Neo4j Ingredient统一的业务编码',
  ingredient_name VARCHAR(120) NOT NULL,
  strength TINYINT UNSIGNED NOT NULL DEFAULT 100 COMMENT '0-100，EXCLUDE默认100',
  is_enabled TINYINT(1) NOT NULL DEFAULT 1,
  preference_source VARCHAR(32) NOT NULL DEFAULT 'USER_INPUT',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uk_user_preference_code (preference_code),
